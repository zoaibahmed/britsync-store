export function translateText(text: string, lang: string): string {
  if (!lang || lang === 'en') return text;
  
  const dict = translationDictionaries[lang.toLowerCase()];
  if (!dict) return text;

  let translated = text;
  Object.keys(dict).forEach((key) => {
    const escapedKey = key.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&');
    translated = translated.replace(new RegExp(escapedKey, 'g'), dict[key]);
  });

  return translated;
}
